let currentLanguage = "pt";
const config = window.GL_CONFIG || {};
const langButton = document.getElementById("language-switch");

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (translations[language][key]) element.innerHTML = translations[language][key];
  });
  langButton.textContent = language === "pt" ? "EN" : "PT";
  langButton.setAttribute("aria-label", language === "pt" ? "Switch to English" : "Mudar para português");
}
langButton.addEventListener("click", () => setLanguage(currentLanguage === "pt" ? "en" : "pt"));

const menuToggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".main-nav");
menuToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}));

document.querySelectorAll(".contact-link").forEach((link) => {
  if (config.whatsapp) {
    link.href = `https://wa.me/${config.whatsapp}`;
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  } else {
    link.href = "#contact";
  }
});

const emailLink = document.getElementById("email-link");
if (config.email) {
  emailLink.href = `mailto:${config.email}`;
  emailLink.textContent = config.email;
}

document.getElementById("contact-form").addEventListener("submit", (event) => {
  event.preventDefault();
  const status = document.getElementById("form-status");
  if (!config.email) {
    status.textContent = translations[currentLanguage].form_no_email;
    return;
  }
  const form = new FormData(event.currentTarget);
  const subject = currentLanguage === "pt" ? "Contato pelo site GL Consulting" : "Website inquiry - GL Consulting";
  const body = [
    `${currentLanguage === "pt" ? "Nome" : "Name"}: ${form.get("name")}`,
    `${currentLanguage === "pt" ? "Empresa" : "Company"}: ${form.get("company") || "-"}`,
    `${currentLanguage === "pt" ? "E-mail" : "Email"}: ${form.get("email")}`,
    "",
    `${currentLanguage === "pt" ? "Mensagem" : "Message"}:`,
    form.get("message")
  ].join("\n");
  status.textContent = translations[currentLanguage].form_success;
  window.location.href = `mailto:${config.email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});

document.getElementById("year").textContent = new Date().getFullYear();
setLanguage("pt");
