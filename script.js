let currentLanguage = "pt";
const config = window.GL_CONFIG || {};
const langButton = document.getElementById("language-switch");

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (Object.prototype.hasOwnProperty.call(translations[language], key)) element.innerHTML = translations[language][key];
  });
  langButton.textContent = language === "pt" ? "EN" : "PT";
  langButton.setAttribute("aria-label", language === "pt" ? "Switch to English" : "Mudar para português");
}
langButton.addEventListener("click", () => setLanguage(currentLanguage === "pt" ? "en" : "pt"));

const menuToggle = document.querySelector(".menu-toggle");
const nav = document.querySelector(".main-nav");
menuToggle.addEventListener("click", () => {
  const isOpen = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});
nav.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => {
  nav.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}));

const emailLink = document.getElementById("email-link");
if (config.email && emailLink) {
  emailLink.href = `mailto:${config.email}`;
  emailLink.textContent = config.email;
}
document.querySelectorAll(".whatsapp-link").forEach((link) => {
  const number = (config.whatsapp || "5541987242085").replace(/\D/g, "");
  link.href = `https://wa.me/${number}`;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
});



const contactForm = document.getElementById("contact-form");
const formStatus = document.getElementById("form-status");
const submitButton = contactForm?.querySelector('button[type="submit"]');

if (contactForm && formStatus && submitButton) {
  contactForm.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (!contactForm.reportValidity()) return;

    const labels = translations[currentLanguage];
    submitButton.disabled = true;
    submitButton.textContent = labels.form_sending;
    formStatus.textContent = "";
    formStatus.className = "form-status";

    try {
      const payload = Object.fromEntries(new FormData(contactForm).entries());
      payload._replyto = payload.email || "";
      const response = await fetch("https://formsubmit.co/ajax/gabrieltlemos@gmail.com", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          "Accept": "application/json"
        },
        body: JSON.stringify(payload)
      });
      const result = await response.json();

      if (String(result.success) !== "true") {
        throw new Error(result.message || "Form submission failed");
      }

      contactForm.reset();
      formStatus.textContent = labels.form_success;
      formStatus.classList.add("form-status-success");
    } catch (error) {
      console.error("Contact form submission error:", error);
      formStatus.textContent = labels.form_error;
      formStatus.classList.add("form-status-error");
    } finally {
      submitButton.disabled = false;
      submitButton.textContent = translations[currentLanguage].form_submit;
    }
  });
}

